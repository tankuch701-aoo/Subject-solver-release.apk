    fun subjectName(category: SubjectCategory): String =
        subjectNames[category] ?: category.displayName

    fun languageModeName(mode: LanguageMode): String =
        languageModeNames[mode] ?: mode.displayName
}

val LocalAppStrings = staticCompositionLocalOf { englishStrings() }

fun getAppStrings(language: AppLanguage): AppStrings = when (language) {
    AppLanguage.ENGLISH -> englishStrings()
    AppLanguage.KHMER -> khmerStrings()
    AppLanguage.FRENCH -> frenchStrings()
    AppLanguage.CHINESE -> chineseStrings()
    AppLanguage.JAPANESE -> japaneseStrings()
    AppLanguage.VIETNAMESE -> vietnameseStrings()
    AppLanguage.SPANISH -> spanishStrings()
}

