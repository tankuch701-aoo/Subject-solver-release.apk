    val appLanguageSectionDesc: String,
    val ocrLanguageSectionTitle: String,
    val ocrLanguageSectionDesc: String,
    val doneLabel: String,
    val copiedToast: String,
    val cameraPermissionRationale: String,
    val imageLoadError: String,
    val emptyCaptureError: String,
